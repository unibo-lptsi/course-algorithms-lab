# Type aliases (cf. labs testing and search), documenting the structure of the data exchanged by the functions below
type SortingAlgorithm = Callable[[list[int]], None] # sort(a) sorts the list a in place
type InputGenerator = Callable[[int, random.Random], list[int]] # gen(n, rnd) returns an input list of length n, using the random generator rnd
type Measures = list[tuple[int, list[float]]] # a list of pairs (n, running times in msec, one for each generated input of length n)

# Number of inputs generated (with different random seeds) for each case and size: the plots show their mean and standard deviation
N_SEEDS = 10

